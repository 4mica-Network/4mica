//! Emits the EIP-712 vectors the other 4Mica SDKs check their signing against.
//!
//! ```text
//! cargo run --example digest_vectors
//! ```

use alloy::primitives::{B256, Bytes, U256};
use rpc::{
    CLEARING_HOUSE_EIP712_NAME, CLEARING_HOUSE_EIP712_VERSION, CheckpointPayload,
    PaymentRequestPayload, ValidationRequirement, clearing_house_domain, recipient_commitment,
};

const CHAIN_ID: u64 = 84532;
const CLEARING_HOUSE: &str = "0x00000000000000000000000000000000000c1ea7";
const PAYER: &str = "0x1234567890123456789012345678901234567890";
const RECIPIENT: &str = "0x00000000000000000000000000000000000000Be";
const ASSET: &str = "0x0000000000000000000000000000000000000000";

fn payment() -> PaymentRequestPayload {
    PaymentRequestPayload::new(
        PAYER.to_string(),
        RECIPIENT.to_string(),
        B256::repeat_byte(0x11),
        U256::from(7u64),
        U256::from(1_000u64),
        1_700_000_000,
        Some(ASSET.to_string()),
        B256::repeat_byte(0x22),
    )
}

fn validated_payment() -> PaymentRequestPayload {
    payment().with_validation(ValidationRequirement {
        validator: "eip155:84532:0x1111111111111111111111111111111111111111".to_string(),
        subject: B256::repeat_byte(0x42),
        deadline: Some(1_700_000_600),
        params: Bytes::from(vec![0xde, 0xad, 0xbe, 0xef]),
    })
}

fn main() {
    let domain = clearing_house_domain(CHAIN_ID, CLEARING_HOUSE.parse().unwrap());
    let recipient = RECIPIENT.parse().unwrap();

    let vector = |payload: &PaymentRequestPayload| {
        serde_json::json!({
            "payload": payload,
            "recipient_commitment": recipient_commitment(
                recipient,
                payload.salt(),
                payload.validation(),
            ),
            "eip712_digest": payload.signing_digest(&domain).unwrap(),
        })
    };

    let checkpoint = CheckpointPayload {
        payer: PAYER.to_string(),
        cycle_id: B256::repeat_byte(0x11),
        asset_address: ASSET.to_string(),
        cumulative_gross: U256::from(1_500u64),
        timestamp_cutoff: 1_700_000_100,
    };

    let out = serde_json::json!({
        "_comment": "Generated by packages/sdk-rust/examples/digest_vectors.rs. Do not edit by hand.",
        "domain": {
            "name": CLEARING_HOUSE_EIP712_NAME,
            "version": CLEARING_HOUSE_EIP712_VERSION,
            "chain_id": CHAIN_ID,
            "verifying_contract": CLEARING_HOUSE,
        },
        "plain": vector(&payment()),
        "validated": vector(&validated_payment()),
        "checkpoint": {
            "payload": checkpoint,
            "eip712_digest": checkpoint.signing_digest(&domain).unwrap(),
        },
    });
    println!("{}", serde_json::to_string_pretty(&out).unwrap());
}
